"""Generate a stand-alone HTML artifact from real k6 and Playwright observations.

Inputs are generated by this workshop. No hard-coded performance results.
"""

import argparse
import html
import json
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_K6 = Path('performance/api-summary.json')
DEFAULT_BROWSER = Path('performance/browser-results.json')
DEFAULT_OUTPUT = Path('performance/protocol-browser-report.html')


def k6_metrics(path):
    """Read both legacy and newer k6 machine-readable summary formats."""
    content = json.loads(path.read_text(encoding='utf-8'))

    # Classic --summary-export: {"metrics": {"http_req_duration": {"values": ...}}}
    metrics = content.get('metrics')
    if isinstance(metrics, dict):
        by_name = metrics
        checks_metrics = metrics
    else:
        # New k6 machine-readable summary: {"results": {"metrics": [{"name": ...}]}}
        results = content.get('results', {})
        metrics_list = results.get('metrics', [])
        if isinstance(metrics_list, dict):
            by_name = metrics_list
        elif isinstance(metrics_list, list):
            by_name = {item['name']: item for item in metrics_list if isinstance(item, dict) and 'name' in item}
        else:
            by_name = {}
        checks_data = results.get('checks', {})
        checks_list = checks_data.get('metrics', []) if isinstance(checks_data, dict) else []
        checks_metrics = (
            {item['name']: item for item in checks_list if isinstance(item, dict) and 'name' in item}
            if isinstance(checks_list, list) else checks_list if isinstance(checks_list, dict) else {}
        )

    def values(collection, name):
        """Accept flat --summary-export metrics or nested handleSummary values."""
        metric = collection.get(name, {})
        if not isinstance(metric, dict):
            return {}
        return metric.get('values', metric)

    duration = values(by_name, 'http_req_duration')
    errors = values(by_name, 'http_req_failed')
    requests = values(by_name, 'http_reqs')
    checks = values(checks_metrics, 'checks') or values(checks_metrics, 'checks_succeeded')

    p95 = duration.get('p(95)', duration.get('p95'))
    if p95 is None:
        keys = list(content.keys())
        raise ValueError(
            f'{path}: cannot find http_req_duration p95. '
            f'Top-level keys: {keys}. Please inspect the exported k6 JSON format.'
        )

    count = int(requests.get('count', 0))
    rps = requests.get('rate')
    if rps is None:
        # The modern JSON format can omit the rate of counters. Use actual run
        # duration only when the export provides it; do not invent an RPS value.
        elapsed_ms = content.get('state', {}).get('testRunDurationMs')
        if isinstance(elapsed_ms, (int, float)) and elapsed_ms > 0:
            rps = count / (elapsed_ms / 1000)

    pass_rate = checks.get('rate', checks.get('value'))
    if pass_rate is None and checks.get('passes') is not None:
        total_checks = checks.get('passes', 0) + checks.get('fails', 0)
        if total_checks:
            pass_rate = checks['passes'] / total_checks
    if pass_rate is None:
        successful = values(checks_metrics, 'checks_succeeded')
        passed_count = successful.get('matches')
        total = successful.get('total')
        if passed_count is not None and total:
            pass_rate = passed_count / total
    if pass_rate is None and isinstance(content.get('root_group'), dict):
        root_checks = content['root_group'].get('checks', {})
        if isinstance(root_checks, dict):
            passed = failed = 0
            for check in root_checks.values():
                if isinstance(check, dict):
                    passed += check.get('passes', 0)
                    failed += check.get('fails', 0)
            if passed + failed:
                pass_rate = passed / (passed + failed)

    return {
        'p95_ms': float(p95),
        'avg_ms': float(duration.get('avg', 0)),
        'error_rate': float(errors.get('rate', errors.get('value', 0))),
        'request_count': count,
        'rps': float(rps) if rps is not None else None,
        'check_pass_rate': float(pass_rate) if pass_rate is not None else None,
    }


